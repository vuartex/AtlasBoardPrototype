"use strict";
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const folder = 'Assets/Project/Scripts/';
const q = read(folder + 'Online/Firebase/AtlasBoardAccountFormQualityGate.cs');
const s = read(folder + 'Online/Firebase/AtlasBoardSteamIdentitySessionFence.cs');
const v = read(folder + 'UI/Menu/AtlasBoardReleaseVersionBadge.cs');
let checks = 0;
function check(cond, label) { assert.ok(cond, label); checks++; }
check(!q.includes('GetInstanceID('), 'No removed Unity GetInstanceID APIs');
check(q.includes('HashSet<TMP_InputField> configuredInputs'), 'Input fields tracked by references');
check(q.includes('HashSet<Button> configuredActions'), 'Buttons tracked by references');
check(q.includes('configuredInputs.Add(input)'), 'Input ID call replaced');
check(q.includes('configuredActions.Add(button)'), 'Button ID call replaced');
check(q.includes('LinkWithCredentialAsync'), 'Guest linking preserved');
check(q.includes('customCaretColor = true'), 'Caret behavior preserved');
check(q.includes('PasswordVisibility'), 'Password toggle preserved');
check(q.includes('EmailFormat.IsMatch'), 'Email validation preserved');
check(s.includes('AtlasBoardSteamReturningSignInResult startupVerified = link != null'), 'Startup steam proof renamed');
check(s.includes('AtlasBoardSteamReturningSignInResult verified = bridge != null'), 'Live steam proof kept');
const startup = s.split('        if (!platform.SteamInitialized || platform.SteamId == 0) return;')[0];
check(!/\bverified\b/.test(startup), 'No shadowed local verified in startup scope');
check(s.includes('startupVerified.SteamId') && s.includes('startupVerified.AccountId'), 'Startup ID/UID proof unchanged');
check(s.includes('verified.SteamId') && s.includes('verified.AccountId'), 'Runtime ID/UID proof unchanged');
check(s.includes('FirebaseAuth.DefaultInstance.SignOut()'), 'Old account session protection preserved');
check(!v.includes('FindObjectsSortMode.None'), 'Deprecated FindObjectsSortMode removed');
check(v.includes('FindObjectsByType<AtlasBoardMainMenuController>('), 'Menu discovery preserved');
check(v.includes('FindObjectsInactive.Include'), 'Inactive menu detection preserved');
check(v.includes('0.9.0-beta.1'), 'Release version unchanged');
console.log(`ATB_PHASE19BN_COMPILE_HOTFIX_SOURCE PASS checks=${checks} unityCompile=NOT_RUN`);
