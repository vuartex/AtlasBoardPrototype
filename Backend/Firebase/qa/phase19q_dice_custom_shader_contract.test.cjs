ok(shader.includes('CBUFFER_START(UnityPerMaterial)'),"SRP Batcher material contract");
ok(shader.includes('#pragma target 3.0'),"Windows and Android GPU target");
ok(meta.includes('guid: 90fb918ce50f4c9b97d823d9ad4315ac'),"Serialized stable shader GUID");
ok(binder.includes('Assets/Project/Shaders/AtlasBoardDiceAtlasUnlit.shader'),"Editor references source shader asset");
ok(binder.includes('AssetDatabase.LoadAssetAtPath<Shader>(DiceAtlasShaderPath)'),"Editor does not guess a shader by name");
