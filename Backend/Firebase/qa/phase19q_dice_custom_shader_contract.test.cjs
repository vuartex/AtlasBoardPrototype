ok(shader.includes('Shader "AtlasBoard/Dice/AtlasUnlitURP"'),"Custom URP ShaderLab asset");
ok(shader.includes('"RenderPipeline" = "UniversalPipeline"'),"URP pipeline tag");
ok(shader.includes('"LightMode" = "UniversalForward"'),"URP forward pass tag");
ok(shader.includes('TransformObjectToHClip'),"Per-vertex position transforms");
