"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname,"../../..");
const read = x => fs.readFileSync(path.join(root,x),"utf8");
const shader = read("Assets/Project/Shaders/AtlasBoardDiceAtlasUnlit.shader");
const meta = read("Assets/Project/Shaders/AtlasBoardDiceAtlasUnlit.shader.meta");
