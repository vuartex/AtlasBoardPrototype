'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const project = path.resolve(__dirname, '../../../');
const base = path.join(project, 'Assets/Project/Scripts');
const panel = fs.readFileSync(path.join(base, 'UI/PlayerHudPanel.cs'), 'utf8');
const picker = fs.readFileSync(path.join(base, 'UI/AtlasBoardEmoteHudRuntime.cs'), 'utf8');
const source19y = fs.readFileSync(path.join(base, 'Meta/AtlasBoardEmoteLoadoutService.cs'), 'utf8');
const scene = fs.readFileSync(path.join(project, 'Assets/Board_Prototype.unity'), 'utf8');
let checks = 0;
function ok(condition, description) { assert.ok(condition, description); checks++; }
ok(panel.includes('IPointerClickHandler'), 'uses existing HUD pointer click interface');
ok(panel.includes('backgroundImage.raycastTarget = true;'), 'HUD raycast is preserved');
ok(!panel.includes('backgroundImage.raycastTarget = false;'), 'old disabling bug absent');
ok(panel.includes('AtlasBoardEmoteHudRuntime.OpenFor(this);'), 'HUD click enters existing runtime');
ok(panel.includes('ATB_EMOTE_HUD_CLICK slot='), 'HUD click event diagnosable');
ok(panel.includes('iconImage.raycastTarget = false;'), 'icon remains non-interactive');
ok(panel.includes('turnBadgeImage.raycastTarget = false;'), 'turn badge remains non-interactive');
ok(panel.includes('target.raycastTarget = false;'), 'HUD text stays non-interactive');
ok(scene.includes('m_Name: HUD_Player_1') && scene.includes('m_Name: HUD_Player_4'), 'existing four HUDs preserved');
ok(scene.includes('m_Name: Canvas_UXOverlay'), 'HUD canvas preserved');
ok(picker.includes('runtime.OpenPopup(panel);'), 'popup shown before remote load');
const openAt = picker.indexOf('runtime.OpenPopup(panel);');
const loadAt = picker.indexOf('await AtlasBoardEmoteLoadoutService.LoadAsync();');
ok(openAt > 0 && openAt < loadAt, 'popup is immediate, remote load comes later');
ok(picker.includes('runtime.popup != null && runtime.activeHud == panel'), 'post-load refresh cannot reopen a dismissed picker');
ok(picker.includes('runtime.currentLocalUid == AtlasBoardRtdbMetaEconomy.CurrentUid'), 'post-load refresh guards UID changes');
ok(picker.includes('ATB_EMOTE_PICKER status=open slot='), 'open event diagnosable');
ok(picker.includes('status=blocked reason=not_local_owner'), 'another player cannot open sender');
ok(picker.includes('status=blocked reason=bot'), 'bots cannot send');
ok(picker.includes('var active=AtlasBoardEmoteLoadoutService.Active.Take(6).ToArray();'), 'six active max maintained');
ok(picker.includes('now-sent<3000'), '3 second cooldown untouched');
ok(picker.includes('if(count>=20)'), '20 emote throttle untouched');
ok(picker.includes('localMute[uid]=now+180000'), '3 minute mute maintained');
ok(picker.includes('AtlasBoardEmoteNetwork.SendAsync(bridge.CurrentLobbyId,id)'), 'online sends via existing RTDB path');
ok(source19y.includes('ids.Count > 6'), 'six-entry loadout guard intact');
ok(!picker.includes('new Button()'), 'no duplicate HUD button or manager');
console.log(`PHASE19Z_EMOTE_HUD_STATIC_QA PASS ${checks}/${checks}`);
