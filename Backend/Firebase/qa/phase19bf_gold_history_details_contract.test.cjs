'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const models=read('Assets/Project/Scripts/Progression/AtlasBoardProgressionModels.cs');
const journal=read('Assets/Project/Scripts/Progression/AtlasBoardRtdbCareerJournal.cs');
const ui=read('Assets/Project/Scripts/UI/Progression/AtlasBoardProgressionUI.cs');
const recorder=read('Assets/Project/Scripts/Progression/AtlasBoardProgressionMatchRecorder.cs');
let checks=0;const ok=(v,m)=>{assert.ok(v,m);checks++;};
ok(models.includes('public int goldAwarded;'),'history model carries match Gold');
ok(models.includes('public AtlasBoardProgressionParticipant[] participants;'),'history model carries participant cards');
ok(journal.includes('PopulateMatchDetailsAsync'),'details are loaded from RTDB proof/archive on demand');
ok(journal.includes('/careerFinalProofs/'),'details use immutable final proof');
ok(journal.includes('/completedMatchArchives/'),'details use immutable completed archive');
ok(journal.includes('String(archive, "seatsJson")'),'participant names come from historical seat roster');
ok(journal.includes('match.goldAwarded = Int(claim, "goldAwarded", 50);'),'history shows actual claim Gold');
ok(journal.includes('RefreshRecentMatchFinalResultsAsync'),'history result is refreshed from final proof');
ok(journal.includes('result == "loss" ? Mathf.Max(2, match.place) : 1'),'tie/win history cannot be downgraded to loss placement');
ok(ui.includes('MatchGoldText(match.goldAwarded)'),'history/details render Gold');
ok(ui.includes('await AtlasBoardRtdbCareerJournal.PopulateMatchDetailsAsync'),'Details fetches historical players');
ok(ui.includes('Historical player data is unavailable for this match.'),'Players panel never stays silently blank');
ok(ui.includes('ParticipantRoleText(participant)'),'player cards show human-facing role context');
ok(recorder.includes('result = kind, place = kind == "loss" ? 2 : 1'),'local tie placement is first-place tie, not loss placement');
console.log(`ATB_PHASE19BF_GOLD_HISTORY_DETAILS_SOURCE PASS checks=${checks} players=historical_archive gold=visible tie=final_proof`);
